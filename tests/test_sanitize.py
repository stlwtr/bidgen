import zipfile

from docx import Document

from bidgen import sanitize


def test_sanitize_removes_machine_and_user_info(tmp_path):
    doc = Document()
    doc.add_paragraph("内容")
    doc.core_properties.author = "python-docx"
    doc.core_properties.last_modified_by = "Some User"
    path = tmp_path / "sample.docx"
    doc.save(str(path))

    sanitize.sanitize_docx(str(path))

    with zipfile.ZipFile(path) as z:
        core = z.read("docProps/core.xml").decode("utf-8")
        app = z.read("docProps/app.xml").decode("utf-8") if "docProps/app.xml" in z.namelist() else ""
        document = z.read("word/document.xml").decode("utf-8")
        settings = z.read("word/settings.xml").decode("utf-8") if "word/settings.xml" in z.namelist() else ""

    assert "python-docx" not in core
    assert "Some User" not in core
    assert "Generated by python" not in core
    assert "Microsoft" not in app
    assert "<w:rsids>" not in settings
    assert "w:rsidR=" not in document

    # Document must still open.
    assert Document(str(path)).paragraphs[0].text == "内容"
